def test_unchanged_data_generates_no_alerts():
    """Comparing the baseline against itself should be quiet."""

    result = compare_fixtures("baseline.geojson")

    assert result["alerts"] == []

    assert result["event_summary"] == {
        "appended": 0,
        "removed": 0,
        "revised": 0,
        "unchanged": 3,
    }


def test_rolling_window_does_not_alert_on_missing_event():
    """An event aging out of a rolling window is not an alert."""

    result = compare_fixtures(
        "missing_event.geojson",
        closed_window=False,
    )

    alert_types = get_alert_types(result)

    assert "EVENTS_REMOVED" not in alert_types

    # The event is still correctly classified as removed.
    assert result["event_summary"]["removed"] == 1
